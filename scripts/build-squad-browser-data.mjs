import { readFile, writeFile } from "node:fs/promises";

function parseCsvLine(line) {
  const cells = [];
  let current = "";
  let quoted = false;
  for (let index = 0; index < line.length; index += 1) {
    const char = line[index];
    if (char === '"' && line[index + 1] === '"') {
      current += '"';
      index += 1;
    } else if (char === '"') {
      quoted = !quoted;
    } else if (char === "," && !quoted) {
      cells.push(current);
      current = "";
    } else {
      current += char;
    }
  }
  cells.push(current);
  return cells;
}

function parseCsv(text) {
  const [headerLine, ...lines] = text.trim().split(/\r?\n/);
  const headers = parseCsvLine(headerLine);
  return lines.map((line) => {
    const cells = parseCsvLine(line);
    return Object.fromEntries(headers.map((header, index) => [header, cells[index] ?? ""]));
  });
}

const csv = await readFile(new URL("../data/squads_2026.csv", import.meta.url), "utf8");
const rows = parseCsv(csv).map((row) => ({
  team: row.team,
  slot: Number(row.slot),
  player: row.player,
  position: row.position,
  age: Number(row.age),
  club: row.club,
  league: row.league,
  marketValueM: Number(row.market_value_m),
  caps: Number(row.caps),
  goals: Number(row.goals),
  injuryStatus: row.injury_status,
  expectedRole: row.expected_role,
  listStatus: row.list_status,
  sourceUrl: row.source_url,
  snapshotDate: row.snapshot_date,
  valueSource: row.value_source,
}));

const output = `// Generated by scripts/build-squad-browser-data.mjs from data/squads_2026.csv.\n` +
  `globalThis.SQUAD_ROWS = Object.freeze(${JSON.stringify(rows)});\n`;

await writeFile(new URL("../data/squads_2026.js", import.meta.url), output);
console.log(`Wrote ${rows.length} squad rows to data/squads_2026.js.`);
